// Writes the three generated guide pages from their data, so they never drift apart:
//   docs/features-status.md    from lib/features.mjs (the stages, what each gates, the checklist counts)
//   docs/compatibility.md      from compat/*.json
//   docs/testing-checklist.md  from testing/checklist.json
//   node scripts/gen-feature-docs.mjs [--check]     --check: exit 1 if a page is out of date (nothing written)
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const DESK = join(dirname(fileURLToPath(import.meta.url)), "..");
process.env.DAYSPRING_CHANNEL ??= "stable";   // the docs describe the builds, not this computer's local choices
const features = await import("../lib/features.mjs");
const compat = await import("../lib/compat.mjs");
const testing = await import("../lib/testing.mjs");
const cell = (s) => String(s ?? "").replace(/\r?\n/g, " ").replace(/\|/g, "\\|");
const STAGE_NAME = { stable: "Stable", beta: "Beta (New)", dev: "In progress (dev)" };
const GENERATED = "<!-- Generated by scripts/gen-feature-docs.mjs from the data; edit the data, then run it again. -->";

function featuresStatus() {
  const items = testing.checklist().items;
  const count = (id) => items.filter((t) => t.feature === id).length;
  const gates = (f) => [f.routes?.length ? `routes ${f.routes.map((r) => "`/api" + r + "`").join(", ")}` : "", f.pages?.length ? `pages ${f.pages.map((x) => "`" + x + "`").join(", ")}` : "",
    f.tools?.length ? `${f.tools.length} AI tool pattern${f.tools.length > 1 ? "s" : ""}` : "", f.intents?.length ? `intents ${f.intents.map((x) => "`" + x + "`").join(", ")}` : "",
    f.sections?.length ? `Settings ${f.sections.map((x) => "`" + x + "`").join(", ")}` : "", f.ui?.length ? `${f.ui.length} screen element${f.ui.length > 1 ? "s" : ""}` : "", f.styles?.length ? "a stylesheet" : "", f.jobs?.length ? `jobs ${f.jobs.map((x) => "`" + x + "`").join(", ")}` : ""].filter(Boolean).join("; ") || "checks `features.on()` in its own code";
  const lines = ["# Feature status", "", GENERATED, "",
    "Which of Dayspring's features are finished, new, or still being built, and which version has them. The owner reviews and changes this list; releases bake his confirmations in (see [Testing checklist](testing-checklist.md)).", "",
    "## The stages", "",
    "- **Stable:** the owner has confirmed it works.",
    "- **Beta (New):** built and passing the automated tests, not yet confirmed. In the production version, marked **New**, with an off switch in Settings → This app → Features.",
    "- **In progress (dev):** still being built. Only in the development version.", "",
    "## The two versions", "",
    "- **Production** (`Dayspring.zip` on the normal releases): stable and beta features.",
    "- **Development** (`Dayspring-dev.zip` on pre-releases, tagged like `v1.7.0-dev.1`): everything. The source checkout counts as development.",
    "- Settings → Updates → **Which versions** picks the channel. Going from development back to production offers the newest production version, with a backup first.",
    "- In a production build, an in-progress feature can only be tried by the developer (the developer preview token), one feature at a time from Settings → Features. Editing files in `data/` can't switch one on.", "",
    "## Every feature", "", "| Feature | id | Area | Stage | Since | Tests | Confirmed |", "|---|---|---|---|---|---|---|"];
  for (const f of features.REGISTRY) lines.push(`| ${cell(f.name)} | \`${f.id}\` | ${cell(f.area)} | ${STAGE_NAME[f.stage]} | ${f.since} | ${count(f.id)} | ${f.verifiedAt ? `${cell(f.verifiedBy ?? "owner")}, ${f.verifiedAt}` : ""} |`);
  for (const stage of ["beta", "dev", "stable"]) {
    lines.push("", `## ${STAGE_NAME[stage]} features`, "");
    for (const f of features.REGISTRY.filter((x) => x.stage === stage)) lines.push(`- **${f.name}** (\`${f.id}\`, since ${f.since}): ${f.description}${stage === "stable" ? "" : ` Hidden when off: ${gates(f)}.`}`);
  }
  lines.push("", "## For developers: the one gate", "",
    "Everything a feature has asks `features.on(\"<id>\")` (`lib/features.mjs`). The registry entry lists what that hides: its `/api` routes answer 404 (server.mjs), its AI tools are left out of `toolsFor` and refused by `runTool` (assistant.mjs), its no-AI intents are skipped (lib/intents/match.mjs), its Settings sections are hidden (public/setup.js), its screen elements are hidden before the page draws (`/api/features/gate.js`, which also sets `window.dsFeatures.on(id)`), and its background jobs are started with `features.startJob(id, name, fn)`, which does nothing while it's off.", "",
    "```js", "import { on } from \"./features.mjs\";      // or: const F = await import(\"../features.mjs\")", "if (!on(\"email\")) return null;             // at every entry point", "```", "");
  return lines.join("\n");
}

function compatibility() {
  const d = compat.load();
  const conn = Object.fromEntries(d.connections.map((c) => [c.id, c.label]));
  const icon = { verified: "✅", "tested-sim": "🧪", expected: "👍", untested: "❔", "not-supported": "⛔" };
  const lines = ["# Compatibility", "", GENERATED, "",
    "The devices, services, browsers and systems Dayspring works with, and how sure we are. Settings → This app → **Compatibility** has the same list, searchable, with the setup steps for each one.", "",
    "- ✅ **Verified:** confirmed on a real device by the owner.",
    "- 🧪 **Passes simulator tests:** Dayspring's automated tests pass against a simulated device of this kind.",
    "- 👍 **Expected to work:** it uses a protocol Dayspring speaks, according to the maker's or the community's documentation.",
    "- ❔ **Untested:** it might work; nobody has tried it yet.",
    "- ⛔ **Not supported:** it can't work with Dayspring (the reason is given).", "",
    "**Works offline** means it keeps working with no internet once it's set up.", "",
    "## Summary", "", "| Category | Total | ✅ | 🧪 | 👍 | ❔ | ⛔ |", "|---|---|---|---|---|---|---|"];
  for (const c of compat.counts()) lines.push(`| ${cell(c.label)} | ${c.total} | ${c.verified} | ${c["tested-sim"]} | ${c.expected} | ${c.untested} | ${c["not-supported"]} |`);
  for (const c of d.categories) {
    lines.push("", `## ${c.label}`, "");
    if (c.description) lines.push(c.description, "");
    lines.push("| Device | Status | Connection | Works offline | Can do | Notes |", "|---|---|---|---|---|---|");
    for (const e of d.entries.filter((x) => x.category === c.id)) lines.push(`| **${cell(e.brand)} ${cell(e.model)}** | ${icon[e.status]} ${e.status} | ${cell(conn[e.connection] ?? e.connection)} | ${e.offline ? "yes" : "no"} | ${cell((e.capabilities ?? []).join(", "))} | ${cell(e.reason ? `Not supported: ${e.reason}` : e.notes)} |`);
  }
  lines.push("");
  return lines.join("\n");
}

function checklistDoc() {
  const c = testing.checklist();
  const names = Object.fromEntries(features.REGISTRY.map((f) => [f.id, f]));
  const lines = ["# Testing checklist", "", GENERATED, "", c.intro, "",
    "The same list is on the **Testing** page (Settings → This app → Testing, in the development version), with Pass / Fail / Skip / Blocked buttons, notes, progress per feature and **Promote to stable**. Its Markdown or CSV export feeds `scripts/promote-features.mjs` for the next release.", "",
    "⚠ marks a step with heat, motion, power or real email sending: read it before you start.", "",
    "## Progress at a glance", "", "| Feature | Stage | Tests |", "|---|---|---|"];
  const order = [...new Set(c.items.map((t) => t.feature))];
  for (const id of order) lines.push(`| ${cell(names[id]?.name ?? id)} | ${STAGE_NAME[names[id]?.stage] ?? ""} | ${c.items.filter((t) => t.feature === id).length} |`);
  for (const id of order) {
    const f = names[id];
    lines.push("", `## ${f?.name ?? id} (${STAGE_NAME[f?.stage] ?? "?"})`, "");
    for (const t of c.items.filter((x) => x.feature === id)) {
      lines.push(`### ${t.id}: ${t.title}`, "");
      const meta = [t.stage ? `Home-control stage ${t.stage}` : "", t.needs?.length ? `You need: ${t.needs.join(", ")}` : ""].filter(Boolean);
      if (meta.length) lines.push(`*${meta.join(" · ")}*`, "");
      if (t.safety) lines.push(`> ⚠ ${t.safety}`, "");
      t.steps.forEach((s, i) => lines.push(`${i + 1}. ${s}`));
      lines.push("", `**Expected:** ${t.expected}`, "", "- [ ] Pass  - [ ] Fail  - [ ] Skip  - [ ] Blocked  Notes: ____", "");
    }
  }
  return lines.join("\n");
}

const pages = { "features-status.md": featuresStatus(), "compatibility.md": compatibility(), "testing-checklist.md": checklistDoc() };
const check = process.argv.includes("--check");
let stale = 0;
for (const [name, text] of Object.entries(pages)) {
  const f = join(DESK, "docs", name);
  let old = ""; try { old = readFileSync(f, "utf8"); } catch { /* new */ }
  if (old === text) { console.log(`up to date  docs/${name}`); continue; }
  if (check) { stale++; console.log(`OUT OF DATE docs/${name}`); continue; }
  writeFileSync(f, text); console.log(`wrote       docs/${name}`);
}
process.exit(check && stale ? 1 : 0);
