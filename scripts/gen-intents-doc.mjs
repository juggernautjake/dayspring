// Writes the "Everything you can say" list in docs/using-without-ai.md from the intent catalogue, so the guide never
// drifts from what Dayspring actually understands. Run after changing lib/intents/catalog*.mjs:
//   node scripts/gen-intents-doc.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const DESK = join(dirname(fileURLToPath(import.meta.url)), "..");
const { INTENTS } = await import(pathToFileURL(join(DESK, "lib", "intents", "catalog.mjs")).href);
const FILE = join(DESK, "docs", "using-without-ai.md");
const FAMILY = {
  time: "Time and dates", schedule: "Your schedule", timers: "Timers, alarms and reminders", focus: "Focus sessions", health: "Health reminders and breaks", home: "Home and meals",
  recipes: "Recipes", cooking: "While you're cooking", everyday: "Math, conversions and quick tools", knowledge: "Quick facts", lists: "Lists, notes and to-dos",
  bible: "The Bible", faith: "Prayer list", weather: "Weather", media: "Music and videos", programs: "Programs, files and websites", jokes: "Jokes", games: "Games",
  chat: "Chatting", social: "How you're feeling", meta: "About the conversation", dayspring: "Dayspring itself", personality: "Personality", study: "Studying", discover: "Discover",
  documents: "Documents", photos: "Photos", phone: "Texts",
};
const ORDER = Object.keys(FAMILY);
// a couple of ready-to-say examples from each intent's phrasings (no {placeholders}, no brackets)
function examples(it) {
  const out = [it.ex];
  for (const t of it.say) {
    if (out.length >= 3) break;
    if (/[{}\[\]()|]/.test(t) || t.length > 60) continue;
    if (!out.some((x) => x.toLowerCase() === t.toLowerCase())) out.push(t);
  }
  return out.map((x) => `“${x.replace(/^./, (c) => c.toUpperCase())}”`);
}
const cats = [...new Set(INTENTS.map((i) => i.cat))].sort((a, b) => (ORDER.indexOf(a) + 99 * (ORDER.indexOf(a) < 0)) - (ORDER.indexOf(b) + 99 * (ORDER.indexOf(b) < 0)));
let md = `<!-- generated by scripts/gen-intents-doc.mjs: ${INTENTS.length} things Dayspring understands without AI -->\n`;
for (const c of cats) {
  md += `\n### ${FAMILY[c] ?? c[0].toUpperCase() + c.slice(1)}\n\n| What it does | Try saying |\n|---|---|\n`;
  for (const it of INTENTS.filter((i) => i.cat === c)) md += `| ${typeof it.label === "string" ? it.label : it.id} | ${examples(it).join(" · ")} |\n`;
}
const doc = readFileSync(FILE, "utf8");
const a = doc.indexOf("<!-- list:start -->"), b = doc.indexOf("<!-- list:end -->");
if (a < 0 || b < 0) throw new Error("docs/using-without-ai.md needs <!-- list:start --> and <!-- list:end -->");
writeFileSync(FILE, doc.slice(0, a + "<!-- list:start -->".length) + "\n" + md + "\n" + doc.slice(b));
console.log(`wrote ${INTENTS.length} intents in ${cats.length} groups to docs/using-without-ai.md`);
