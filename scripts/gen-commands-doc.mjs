// Writes docs/things-you-can-say.md (the "Things you can say" page of the guide) from the command grammar itself, so the
// page never drifts from what Dayspring understands without AI:
//   the settings table   from lib/commands/settings-voice.mjs SCHEMA (every setting, with phrasings made from its names)
//   everything else      from scripts/qa/commands-golden.mjs (phrasings the tests check word for word, every run)
//   the default times    from lib/commands/when.mjs PART_TIMES
//   node scripts/gen-commands-doc.mjs [--check]     --check: exit 1 if the page is out of date (nothing written)
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const DESK = join(dirname(fileURLToPath(import.meta.url)), "..");
const FILE = join(DESK, "docs", "things-you-can-say.md");
const imp = (p) => import(pathToFileURL(join(DESK, p)).href);
const S = await imp("lib/commands/settings-voice.mjs");
const { PART_TIMES } = await imp("lib/commands/when.mjs");
const { COMMANDS_GOLDEN } = await imp("scripts/qa/commands-golden.mjs");
const { sayTime } = await imp("lib/intents/slots.mjs");

// the tested phrasings, by kind
const byIntent = new Map(), byLine = new Map();
for (const line of COMMANDS_GOLDEN.split("\n").map((l) => l.trim()).filter(Boolean)) {
  const [intent, json, phrases] = line.split(" ~ ");
  if (phrases) byLine.set(`${intent} ${json}`, phrases.split("|").map((x) => x.trim()).filter(Boolean));
  if (!phrases || intent === "none") continue;
  const list = byIntent.get(intent) ?? [];
  for (const p of phrases.split("|").map((x) => x.trim()).filter(Boolean)) if (!list.includes(p)) list.push(p);
  byIntent.set(intent, list);
}
const q = (p) => `“${p.replace(/^./, (c) => c.toUpperCase())}”`;
const some = (intent, n = 4) => (byIntent.get(intent) ?? []).slice(0, n).map(q).join(" · ");
// the phrasings of one kind whose expected details pass a test: pick("sky.weather", (w) => w.args.minutes, 3)
// (a few from each group in turn, so the examples show the range: "make it rain", "let it snow", "thunderstorm"…)
const pick = (intent, test = () => true, n = 4) => { const groups = []; for (const [k, list] of byLine) { const [i, ...j] = k.split(" "); if (i !== intent) continue; let w = {}; try { w = JSON.parse(j.join(" ")); } catch { /* no details */ } if (!w.closing && test(w)) groups.push(list); } const out = []; for (let r = 0; r < 12 && out.length < n * 3; r++) for (const g of groups) if (g[r] && !out.includes(g[r])) out.push(g[r]); return out.filter((p, x, a) => a.findIndex((y) => y.toLowerCase().replace(/[^a-z0-9]/g, "") === p.toLowerCase().replace(/[^a-z0-9]/g, "")) === x).slice(0, n).map(q).join(" · "); };
const some2 = (intent, n = 4) => (["pass", "close"].includes(intent) ? some(intent, n) : pick(intent, undefined, n));
const row = (what, ...intents) => `| ${what} | ${intents.map((i) => some2(i, 3)).filter(Boolean).join(" · ")} |`;
const cell = (s) => String(s).replace(/\|/g, "\\|");

const md = [];
md.push("# Things you can say", "");
md.push("<!-- Generated by scripts/gen-commands-doc.mjs from the command grammar and its tests; edit those, then run it again. -->", "");
md.push("Everything on this page works **without an AI brain**, on your computer, in a few milliseconds. Say it the way you normally would: Dayspring ignores \"um\", \"please\", \"could you\" and \"hey Dayspring\", understands numbers said as words (\"twenty five\"), and fixes common mishearings (\"set a time her\"). Every example here is checked by the automated tests on every build.", "");
md.push("**Ending the conversation** and **Stop** (below) are in every version since 1.7.3 (Settings → This app → Features: **Stop and goodbye**). The rest of these commands are new in the development version (1.8.0), listed there as **Everyday commands without AI**. A reminder at a clock time (“remind me to drink water at 11pm”) works in every version. For the full list of everyday requests (timers, the Bible, recipes, math and more), see [Using Dayspring without AI](using-without-ai.md).", "");

md.push("## Ending the conversation", "");
md.push("When you're done, just say so. Dayspring answers briefly and stops listening right away, instead of waiting for more. Tacked onto a request (\"set a timer for 5 minutes, thanks\"), it does the request and asks no follow-up question.", "");
const kind = (k, n = 6) => (byLine.get(`close {"args":{"kind":"${k}"}}`) ?? []).slice(0, n).map(q).join(" · ");
md.push(`- Thanks: ${kind("thanks")}`);
md.push(`- Done: ${kind("done", 8)}`);
md.push(`- Goodbye: ${kind("bye")} · ${kind("night", 3)}`);
md.push(`- Never mind: ${kind("nevermind", 3)}`);
md.push(`- On the end of a request: ${some2("pass", 3)}`);
md.push("- Not an ending: \"thanks for the reminder, now set a timer for 10 minutes\" sets the timer; \"never mind the timer, cancel it\" cancels it; \"remind me to say thank you at 5\" is a reminder.", "");
md.push("If Dayspring just asked you something, \"no thanks\" or \"that's all\" answers it (nothing happens) and ends the conversation.", "");
md.push("### Stop", "");
md.push("Say **\"stop\"**, \"that's enough\", \"enough\", \"shh\", \"hush\", \"be quiet\", \"cancel\", \"never mind\", \"okay that's good\" or \"got it, thanks\" on its own, even while Dayspring is talking, and it stops right away: mid-sentence, the rest of the reply, a document being read aloud, and any question it was asking. It doesn't say \"okay, stopping\". Only this conversation ends: Dayspring keeps listening for its name, so the next \"Dayspring, …\" works at once. (✋ Stop, the mic button, \"stop listening\" and \"go to sleep\" are what stop listening altogether.)", "");
md.push("Music and videos keep playing when you stop Dayspring's voice. A plain \"Dayspring, stop\" while nothing is being said stops the music; \"stop the music\", \"stop the timer\" and \"stop the alarm\" always mean just that.", "");

md.push("## Every setting", "");
md.push("Any setting can be changed and asked about by voice: turn it on or off, set a value, make it bigger or smaller, louder or quieter, reset it, or ask what it's set to. Dayspring always says what changed. **\"Undo that\"** puts the last change back.", "");
md.push("| Setting | Try saying |", "|---|---|");
for (const e of S.examples()) {
  if (e.security === "settings") { md.push(`| ${cell(e.label.replace(/^./, (c) => c.toUpperCase()))} | Only in Settings (Dayspring tells you where) |`); continue; }
  if (e.delegate) { md.push(`| ${cell(e.label.replace(/^./, (c) => c.toUpperCase()))} | ${e.examples.map((x) => q(x.replace(/ \(.*\)$/, ""))).join(" · ")} (see [Settings reference](settings-reference.md)) |`); continue; }
  md.push(`| ${cell(e.label.replace(/^./, (c) => c.toUpperCase()))}${e.security === "confirm" ? " 🔒" : ""} | ${e.examples.slice(0, 3).map(q).join(" · ")} |`);
}
md.push("", "🔒 A security setting: Dayspring says what it would change and waits for your **yes**. Giving access to all your files, the folders it uses, the money review and your location's details are changed only in Settings.", "");
md.push("Some everyday ones:", "");
for (const i of ["setting.set", "setting.adjust", "setting.get", "setting.reset", "undo"]) md.push(`- ${pick(i, (w) => !/^(files|web|deleteFiles|programs|browser|claudeCode|money|wakeWords)$/.test(w.args?.id ?? ""), 6)}`);
md.push("");

md.push("## The sky, the background and the screen", "");
md.push("| What | Try saying |", "|---|---|");
md.push(`| Weather on the screen | ${pick("sky.weather", (w) => !w.args?.minutes, 8)} |`);
md.push(`| For a while, then back by itself | ${pick("sky.weather", (w) => w.args?.minutes, 3)} · ${pick("sky.phase", (w) => w.args?.minutes, 1)} |`);
md.push(`| Time of day | ${pick("sky.phase", (w) => !w.args?.minutes, 6)} |`);
md.push(row("Back to the real sky", "sky.real"));
