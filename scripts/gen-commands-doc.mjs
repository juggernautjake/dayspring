const out = md.join("\n") + "\n";
if (process.argv.includes("--check")) {
  const now = existsSync(FILE) ? readFileSync(FILE, "utf8") : "";
  if (now !== out) { console.log("docs/things-you-can-say.md is out of date: run node scripts/gen-commands-doc.mjs"); process.exit(1); }
  console.log("docs/things-you-can-say.md is up to date"); process.exit(0);
}
writeFileSync(FILE, out);
console.log(`wrote docs/things-you-can-say.md (${S.SCHEMA.length} settings, ${[...byIntent.values()].reduce((a, b) => a + b.length, 0)} tested phrasings to pick from)`);
process.exit(0);
