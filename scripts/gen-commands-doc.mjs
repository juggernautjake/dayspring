md.push(`| The layout | ${pick("setting.set", (w) => /^(layout|density)$/.test(w.args?.id ?? ""), 5)} |`);
md.push(`| What's shown | ${pick("setting.set", (w) => /^show/.test(w.args?.id ?? ""), 5)} |`);
md.push(`| Sizes | ${pick("setting.adjust", (w) => /Scale$|talkWidth/.test(w.args?.id ?? ""), 5)} |`);
md.push("", "Add \"for 10 minutes\" (or \"for an hour\") to any sky change and it goes back by itself. The scenery Dayspring has is hills, fields, forest and river; for anything else (\"mountains\", \"the beach\") it picks the closest and tells you.", "");

md.push("## Your schedule, with repeats", "");
md.push(`- Add: ${some2("sched.create", 6)}`);
md.push(`- Move: ${some2("sched.move", 5)}`);
md.push(`- Cancel one, or a day of a repeating one: ${some2("sched.cancel", 5)}`);
md.push(`- Make it repeat, or change how often: ${some2("sched.recur", 5)}`);
md.push(`- Stop repeating: ${some2("sched.norecur", 4)}`);
md.push("", "How often: every day, weekdays, weekends, weeknights (Monday to Friday), every Monday Wednesday and Friday, every other week (or every other Friday), every 3 weeks, the first Monday of every month, the last Friday of the month, the 15th of each month, every year; with \"until December\" (through November 30), \"until December 15\", \"for the next 3 weeks\", \"starting next Monday\", \"except holidays\" (US federal holidays) or \"every day except Sunday\".", "");
md.push("When: today, tonight, tomorrow, this weekend (Saturday), next Tuesday, in 3 days, next month on the 5th, October 12th, at noon, half past 6, quarter to 9, from 3 to 5, for an hour. Times of day on their own:", "");
md.push("| Said | Means |", "|---|---|");
for (const [k, v] of Object.entries(PART_TIMES)) md.push(`| ${k} | ${sayTime(v)} |`);
md.push("", "A bare hour from 1 to 6 means p.m. and 7 to 11 means a.m., unless the words say otherwise (\"at 9 tonight\", \"every weeknight at 9\" → 9 p.m.). For a one-time item with no day, it's whichever comes next. For a repeating one at 7 to 11 with no a.m. or p.m., Dayspring asks once.", "");

md.push("## Reminders", "");
md.push(`- Once, at a time: ${pick("reminder.create", (w) => !w.args?.repeat && !w.args?.needText, 5)} (today, or tomorrow once the time has passed; never every hour)`);
md.push(`- Repeating: ${pick("reminder.create", (w) => w.args?.repeat, 5)}`);
